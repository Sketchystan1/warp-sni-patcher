/* Initialize language: checks command line / env vars / system language. */
void I18nInit(const char* cmdLine);

/* Returns TRUE if Russian language is currently active. */
BOOL I18nIsRussian(void);

/* Explicitly set Russian (TRUE) or English (FALSE) mode. */
void I18nSetRussian(BOOL isRussian);

/* Toggle between Russian and English mode. */
void I18nToggleLanguage(void);

/* Returns translated UTF-8 string. */
const char* Tr(StringId id);

/* Returns translated wide (UTF-16) string. */
const wchar_t* TrW(StringId id);

